// Phone e2e (393×852): upload → captions → the editor opens on the automatic FULL edit → Auto edit
// sheet → removed lines → restore one → try another hook → cuts only → back to full edit.
import { createRequire } from "node:module";
const SC = "/private/tmp/claude-501/-Users-christophercorallo-Desktop-Claude-Projects-Chris-Socials/2fa27366-298a-4c40-a49e-d2c8b0f369a9/scratchpad";
const require = createRequire(`${SC}/pw/node_modules/`);
const { chromium } = require("playwright");
const base = "http://localhost:3671";
const out = `${SC}/fulledit/shot`;
const take = process.argv[2] ?? "t3";
const b = await chromium.launch({ channel: "chrome" });
const p = await (await b.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })).newPage();
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
p.on("dialog", (d) => {
  console.log("DIALOG:", d.message());
  void d.accept();
});
const t0 = Date.now();
const log = (...a) => console.log(`[${((Date.now() - t0) / 1000).toFixed(1)}s]`, ...a);
const hidePortal = () => p.addStyleTag({ content: "nextjs-portal{display:none!important}" }).catch(() => {});
await p.goto(`${base}/login`, { timeout: 240000 });
await p.fill('input[name="email"]', "chris@example.com");
await p.fill('input[name="password"]', "flowtest-123");
await p.click('button[type="submit"]');
await p.waitForURL((u) => !u.pathname.startsWith("/login"), { timeout: 120000 });
await p.goto(`${base}/upload`, { waitUntil: "networkidle", timeout: 240000 });
await p.fill("input.field-input", "Full edit test — emergency fund");
await p.setInputFiles('input[type="file"]', `${SC}/fulledit/${take}.mp4`);
log("uploading…");
await p.waitForURL(/\/edit$/, { timeout: 600000 });
log("editor:", p.url());
await p.waitForTimeout(2500);
await hidePortal();
await p.screenshot({ path: `${out}-1-editor.png` });
log("toasts:", JSON.stringify(await p.locator(".ed-toast").allInnerTexts()));
await p.getByRole("button", { name: "Auto edit" }).first().click();
await p.waitForTimeout(1200);
await hidePortal();
await p.screenshot({ path: `${out}-2-sheet.png` });
log("summary:", (await p.locator("[data-testid=full-edit-summary]").innerText().catch(() => "NONE")).replace(/\n+/g, " | ").slice(0, 600));
await p.locator("[data-testid=removed-lines-toggle]").click();
await p.waitForTimeout(500);
await p.locator("[data-testid=removed-lines]").scrollIntoViewIfNeeded();
await p.screenshot({ path: `${out}-3-removed.png` });
log("removed:", (await p.locator("[data-testid=removed-lines]").innerText()).replace(/\n+/g, " | ").slice(0, 600));
await p.locator("[data-testid=removed-lines] button", { hasText: "Restore" }).first().click();
await p.waitForSelector("[data-testid=full-edit-length]", { timeout: 120000 });
await p.waitForTimeout(6000);
log("after restore:", await p.locator("[data-testid=full-edit-length]").innerText());
await p.getByRole("button", { name: "Try another hook" }).click();
await p.waitForTimeout(9000);
await hidePortal();
await p.locator("[data-testid=full-edit-summary]").scrollIntoViewIfNeeded();
await p.screenshot({ path: `${out}-4-another-hook.png` });
log("after another hook:", (await p.locator("[data-testid=full-edit-summary] p").first().innerText()));
await p.locator("[data-testid=auto-edit-cuts]").scrollIntoViewIfNeeded();
await p.locator("[data-testid=auto-edit-cuts]").click();
await p.waitForTimeout(8000);
await hidePortal();
await p.screenshot({ path: `${out}-5-cuts.png` });
log("versions title:", await p.locator(".ed-m-titlewrap p").innerText().catch(() => "?"));
await p.locator("[data-testid=auto-edit-full]").click();
await p.waitForTimeout(9000);
await p.keyboard.press("Escape");
await p.waitForTimeout(800);
await hidePortal();
await p.screenshot({ path: `${out}-6-preview.png` });
await b.close();
