/**
 * Asset manifest for mini-movies (spec §15: store type, source/license, AI-generated yes/no).
 * Every model, font, sound, texture or library a rendered film depends on is listed here with
 * where it came from and under what license — verified from the source on the date given.
 * A test fails if an entry lacks a license field, so nothing unlicensed can slip in.
 */

export type AssetKind = "MODEL_3D" | "TEXTURE" | "HDRI" | "FONT" | "SFX" | "MUSIC" | "TTS_MODEL" | "TTS_VOICE" | "LIBRARY" | "PROCEDURAL";

export interface AssetEntry {
  id: string;
  kind: AssetKind;
  /** What it is used for in a film. */
  usage: string;
  /** Where it comes from: "original (generated by <file>)" or the publisher. */
  source: string;
  url: string | null;
  /** SPDX-style identifier or a short license name. */
  license: string;
  licenseUrl: string | null;
  /** Date the license was checked (YYYY-MM-DD). */
  verified: string;
  /** How it reaches a render: in repo / fetched at runtime into a cache / npm dependency. */
  delivery: "IN_REPO" | "RUNTIME_DOWNLOAD" | "NPM" | "CODE";
  aiGenerated: boolean;
  attributionRequired: boolean;
  notes?: string;
}

