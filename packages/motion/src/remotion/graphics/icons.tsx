/**
 * A line icon. `draw` (0..1) strokes it on (each path in turn) — 1 = fully drawn. Stroke width
 * is in icon units (24-grid), scaled with `size`.
 */
export function GIcon({ icon, size, color, draw = 1, stroke = 1.8, glow }: { icon: GraphicIcon; size: number; color: string; draw?: number; stroke?: number; glow?: string }) {
  const paths = GRAPHIC_ICON_PATHS[icon];
  const n = paths.length;
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" style={{ display: "block", overflow: "visible", filter: glow ? `drop-shadow(0 0 ${Math.round(size * 0.12)}px ${glow})` : undefined }}>
      {paths.map((d, i) => {
        const t = draw >= 1 ? 1 : Math.max(0, Math.min(1, draw * n - i * 0.7));
        return (
          <path
            key={i}
            d={d}
            fill="none"
            stroke={color}
            strokeWidth={stroke}
            strokeLinecap="round"
            strokeLinejoin="round"
            pathLength={1}
            strokeDasharray={t >= 1 ? undefined : "1 1"}
            strokeDashoffset={t >= 1 ? undefined : 1 - t}
          />
        );
      })}
    </svg>
  );
}
